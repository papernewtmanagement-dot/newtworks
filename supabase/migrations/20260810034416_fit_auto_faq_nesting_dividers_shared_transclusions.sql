<details>
<summary>FAQ: Drive Safe and Save</summary>

- **How much will I actually save?** The discount starts at 10%. The average Texas driver saves 16%, and safer drivers save more.
- **How do I sign up?** Text SAVE to 78836 to check that your phone is compatible. Then download the State Farm app, tap Drive Safe & Save, and follow the setup steps. State Farm will mail you a small Bluetooth beacon that sticks to your windshield.
- **How does the app know when I'm driving?** Your phone connects to the beacon when you're in the car, and the app records the trip automatically. You don't have to open the app or press anything — just keep your phone with you and drive.
- **What if my trips aren't showing up?** Restart your phone, log out and back into the app, and make sure it has permission for location and physical activity. If the beacon's red light won't come on, call 1-888-559-1922 for a new one.

