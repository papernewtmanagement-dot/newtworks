<details>
<summary>FAQ: Advanced Product Situations</summary>

- **What if my vehicle is used for my business?** Vehicles over 10,000 lb GVW, delivery vehicles, or those with employee drivers write on the Business Car Policy. Regular cars owned by a business may still qualify for the Personal Car Policy if usage is under 50% business. Sedans or coupes titled to a corporation need underwriting review before quoting.
- **What if I've got a farm or ranch?** To qualify for farm rates the vehicle has to be garaged at the farm, can't be used to commute to a regular job, and can only be used for farming or the customer's own operations. The customer also has to actually raise a crop or animal for profit — living on land isn't enough.
- **What if State Farm can't insure me?** GAINSCO is the non-standard placement route. Accepts foreign licenses (Mexican Matricula, international), suspended or expired licenses without SR-22, salvage titles up to 30 years old, and drivers with no license. Sales support: 866-805-1344.
- **What kinds of vehicles can't be insured?** Motorcycles, RVs, motorhomes, campers, travel trailers, dune buggies, ATVs, hearses, limousines, and flatbeds. Also rare, antique, classic, custom, electric, kit, race replica, and vehicles built for speed. Motorcycles go through the SF Motorcycle program; specialty vehicles need a specialty carrier.

</details>

